const DICTS: Record<Lang, Partial<Dict>> = { en, pt, es };

export type TKey = keyof Dict;

export function translate(lang: Lang, key: TKey): string {
  return (DICTS[lang][key] as string | undefined) ?? en[key];
}

export function useT() {
  const lang = useStore((s) => s.lang);
  return (key: TKey) => translate(lang, key);
}

export function locale(lang: Lang): string {
  return lang === "pt" ? "pt-BR" : lang === "es" ? "es-ES" : "en-US";
}
